CREATE OR REPLACE FUNCTION public.abrir_chat_al_interesarse()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  -- Un match por par pedido/proveedor. Si la app ya lo habia sugerido y el
  -- proveedor ademas se anota, no se duplica la conversacion: se deja la que
  -- ya existe, que puede tener mensajes adentro.
  if exists (
    select 1 from public.matches
    where solicitud_id = new.solicitud_id
      and proveedor_id = new.proveedor_id
  ) then
    return new;
  end if;

  -- 'interesado' se distingue a proposito de 'sugerido': uno lo armo la app,
  -- el otro lo pidio el proveedor. La app los muestra distinto, porque
  -- decirle "te lo recomendamos" a alguien que se ofrecio solo seria falso.
  insert into public.matches (solicitud_id, proveedor_id, estado)
  values (new.solicitud_id, new.proveedor_id, 'interesado');

  -- El pedido deja de estar "buscando" en la pantalla del cliente.
  update public.solicitudes
     set estado = 'con_match'
   where id = new.solicitud_id
     and estado = 'pendiente';

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.borrar_mi_cuenta(motivo_baja text DEFAULT NULL::text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth'
AS $function$
declare
  yo        uuid := auth.uid();
  mi_rol    text;
  mis_prov  uuid[];
  mis_sol   uuid[];
  mis_match uuid[];
  borradas  int := 0;
begin
  -- Nunca confiar en un id que venga de afuera: se usa el del token.
  if yo is null then
    raise exception 'sin sesión';
  end if;

  select coalesce(raw_user_meta_data->>'rol', 'cliente')
    into mi_rol from auth.users where id = yo;

  -- Qué es mío, resuelto una sola vez
  select coalesce(array_agg(id), '{}') into mis_prov
    from public.proveedores where user_id = yo;

  select coalesce(array_agg(id), '{}') into mis_sol
    from public.solicitudes where user_id = yo;

  select coalesce(array_agg(id), '{}') into mis_match
    from public.matches
    where solicitud_id = any(mis_sol) or proveedor_id = any(mis_prov);

  -- ── Calificaciones ────────────────────────────────────────────────────
  -- Las que YO dejé sobre un Proveedor: sobreviven, pero dejan de decir
  -- quién las dejó. Es la reputación de otra persona, no mía.
  update public.reputacion
     set cliente_user_id = null,
         match_id        = null
   where cliente_user_id = yo;

  -- Las que son SOBRE MÍ como Proveedor: se van con el perfil. Sin perfil
  -- no hay reputación que sostener.
  delete from public.reputacion where proveedor_user_id = yo;

  -- ── Conversaciones ────────────────────────────────────────────────────
  delete from public.mensajes    where match_id = any(mis_match);
  delete from public.matches     where id       = any(mis_match);
  delete from public.interesados where user_id  = yo or solicitud_id = any(mis_sol);

  -- ── Pedidos y perfiles ────────────────────────────────────────────────
  delete from public.solicitudes      where user_id = yo;
  delete from public.publicaciones    where user_id = yo;
  delete from public.credenciales     where user_id = yo;
  delete from public.perfil_proveedor where user_id = yo;
  delete from public.proveedores      where user_id = yo;

  -- ── Rastros de uso ────────────────────────────────────────────────────
  delete from public.consultas      where user_id        = yo;
  delete from public.canjes         where user_id        = yo;
  delete from public.visitas_perfil where perfil_user_id = yo;

  -- CONFIRMAR: si 'visitante' guarda el id del usuario que visitó, esta
  -- línea hace falta y hay que descomentarla. Si guarda otra cosa (una IP,
  -- un identificador de sesión), dejala comentada y decime qué guarda.
  -- delete from public.visitas_perfil where visitante = yo::text;

  -- ── Mercado Pago ──────────────────────────────────────────────────────
  -- Acá viven access_token y refresh_token: credenciales vivas. Borrar la
  -- fila es obligatorio, pero NO revoca el permiso del lado de Mercado
  -- Pago. Eso hay que hacerlo con su API, desde n8n, antes de llamar acá.
  delete from public.cuentas_mp where user_id = yo;

  -- ── Lo que sobrevive ──────────────────────────────────────────────────
  -- El punto 6.1 de la Política conserva el registro contable de las
  -- operaciones cobradas: identificador, fecha, monto, comisión, CUIT y
  -- número de comprobante.
  --
  -- HOY NO SE CONSERVA NADA, y es correcto: no existe todavía la tabla de
  -- operaciones cobradas ni la emisión de comprobantes, así que no hay
  -- registro contable que guardar. La promesa se cumple de forma vacía.
  --
  -- Cuando exista esa tabla, va acá el UPDATE que desvincula la operación
  -- de la persona conservando los campos fiscales. No antes.

  -- ── Motivo, sin dueño ─────────────────────────────────────────────────
  if motivo_baja is not null and length(trim(motivo_baja)) > 0 then
    insert into public.bajas (motivo, era_de) values (trim(motivo_baja), mi_rol);
  end if;

  -- ── La cuenta ─────────────────────────────────────────────────────────
  delete from auth.users where id = yo;
  get diagnostics borradas = row_count;

  return json_build_object('ok', true, 'cuenta_borrada', borradas = 1);
end;
$function$
;

CREATE OR REPLACE FUNCTION public.chequear_cupo()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  tomados int;
  limite  int;
begin
  -- El for update serializa: dos proveedores que toquen "me interesa" en el
  -- mismo instante no pueden pasar los dos el chequeo.
  select cupo into limite from public.solicitudes where id = new.solicitud_id for update;
  if limite is null then
    raise exception 'ese pedido no existe' using errcode = 'P0002';
  end if;

  select count(*) into tomados from public.interesados where solicitud_id = new.solicitud_id;
  if tomados >= limite then
    raise exception 'ese pedido ya tiene el cupo completo' using errcode = 'P0001';
  end if;

  return new;
end;
$function$
;

