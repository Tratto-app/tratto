CREATE OR REPLACE FUNCTION public.notificar_evento_push()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'net'
AS $function$
declare
  destinatario   uuid;
  titulo         text;
  cuerpo         text;
  url_push       text := 'https://qglsonbcsncgekzbfafk.supabase.co/functions/v1/quick-service';
  secreto        text;
  rubro          text;
begin
  if coalesce(new.tipo, '') <> 'presupuesto' then
    return new;
  end if;

  -- ── 1) Presupuesto nuevo → avisarle al cliente ─────────────────────────
  if tg_op = 'INSERT' and coalesce(new.estado_presupuesto,'') = 'pendiente' then
    select s.user_id, s.servicio_necesitado into destinatario, rubro
      from public.matches m
      join public.solicitudes s on s.id = m.solicitud_id
     where m.id = new.match_id;

    titulo := 'Te llegó un presupuesto';
    cuerpo := 'Te ofrecieron ' || to_char(new.monto, 'FM999G999G999') || ' pesos' ||
              (case when rubro is not null then ' para tu pedido de ' || rubro else '' end) ||
              '. Mirá los detalles.';

  -- ── 2) Presupuesto aceptado → avisarle al proveedor ────────────────────
  elsif tg_op = 'UPDATE'
        and new.estado_presupuesto = 'aceptado'
        and old.estado_presupuesto is distinct from 'aceptado' then

    select p.user_id into destinatario
      from public.matches m
      join public.proveedores p on p.id = m.proveedor_id
     where m.id = new.match_id;

    titulo := 'Te aceptaron un presupuesto';
    cuerpo := 'Te aceptaron el de ' || to_char(new.monto, 'FM999G999G999') || ' pesos. Ya podés arrancar.';

  -- ── 3) Presupuesto rechazado → avisarle al proveedor ───────────────────
  elsif tg_op = 'UPDATE'
        and new.estado_presupuesto = 'rechazado'
        and old.estado_presupuesto is distinct from 'rechazado' then

    select p.user_id into destinatario
      from public.matches m
      join public.proveedores p on p.id = m.proveedor_id
     where m.id = new.match_id;

    titulo := 'No te aceptaron este presupuesto';
    cuerpo := 'Podés mandar otro con otras condiciones si querés.';

  -- ── 4) Trabajo marcado terminado → avisarle al cliente ─────────────────
  elsif tg_op = 'UPDATE'
        and new.trabajo_estado = 'terminado'
        and old.trabajo_estado is distinct from 'terminado' then

    select s.user_id into destinatario
      from public.matches m
      join public.solicitudes s on s.id = m.solicitud_id
     where m.id = new.match_id;

    titulo := 'Marcaron tu pedido como terminado';
    cuerpo := 'Revisalo y pagalo cuando estés conforme.';

  -- ── 5) Pago cobrado → avisarle al proveedor ────────────────────────────
  elsif tg_op = 'UPDATE'
        and new.pago_estado = 'cobrado'
        and old.pago_estado is distinct from 'cobrado' then

    select p.user_id into destinatario
      from public.matches m
      join public.proveedores p on p.id = m.proveedor_id
     where m.id = new.match_id;

    titulo := 'Te pagaron';
    cuerpo := 'Se acreditaron ' || to_char(new.monto, 'FM999G999G999') || ' pesos por tu trabajo.';

  else
    return new;
  end if;

  if destinatario is null then
    return new;
  end if;

  select decrypted_secret into secreto
    from vault.decrypted_secrets where name = 'push_firma_quick_service';

  perform net.http_post(
    url     := url_push,
    body    := jsonb_build_object(
                 'user_id', destinatario,
                 'titulo',  titulo,
                 'cuerpo',  cuerpo,
                 'url',     '/',
                 'tipo',    'servicio'
               ),
    headers := jsonb_build_object(
                 'Content-Type', 'application/json',
                 'x-tratto-firma', secreto
               )
  );

  return new;
exception
  when others then
    return new;
end;
$function$
