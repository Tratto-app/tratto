CREATE OR REPLACE FUNCTION public.sumar_trabajo()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.tipo = 'presupuesto'
     and new.estado_presupuesto = 'aceptado'
     and old.estado_presupuesto is distinct from 'aceptado' then
    update perfil_proveedor pp
       set trabajos_hechos = coalesce(pp.trabajos_hechos, 0) + 1
      from matches m
      join proveedores p on p.id = m.proveedor_id
     where m.id = new.match_id and pp.user_id = p.user_id;
  end if;
  return new;
end $function$
;

